import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  customType,
  date,
  foreignKey,
  index,
  integer,
  pgEnum,
  pgTable,
  smallint,
  text,
  time,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
  type AnyPgColumn,
} from 'drizzle-orm/pg-core';

/**
 * PostgreSQL `tstzrange`, kept as its text form (e.g. `["2026-10-20 09:00:00+00","…")`).
 * Application code uses `start_at`/`end_at`; the range exists for constraints and
 * overlap queries (see `rangeOverlaps`). ADR-0002.
 */
export const tstzrange = customType<{ data: string; driverData: string }>({
  dataType: () => 'tstzrange',
});

/** PostgreSQL `bytea` as a Node.js Buffer. */
export const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType: () => 'bytea',
});

const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

const timestamps = {
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  updatedAt: timestamptz('updated_at')
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
};

// ---------------------------------------------------------------------------------------------
// Auth (Better Auth models, ADR-0004). Property names are Better Auth's field names; SQL column
// names are snake_case. Ids are UUIDs, generated by Better Auth or by Postgres.
// ---------------------------------------------------------------------------------------------

export const users = pgTable(
  'users',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    email: text('email').notNull().unique(),
    emailVerified: boolean('email_verified').notNull().default(false),
    name: text('name').notNull(),
    image: text('image'),
    /** Public booking link `/{username}/{slug}`. Reserved names are rejected in the app. */
    username: text('username').notNull().unique(),
    /** IANA time zone, validated in the app. */
    timeZone: text('time_zone').notNull(),
    ...timestamps,
  },
  (t) => [
    check('users_email_lowercase', sql`${t.email} = lower(${t.email})`),
    check('users_username_format', sql`${t.username} ~ '^[a-z0-9](?:[a-z0-9-]{1,38}[a-z0-9])$'`),
  ],
);

export const sessions = pgTable(
  'sessions',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** SHA-256 (base64url) of the session token; the raw token only lives in the cookie. */
    token: text('token_hash').notNull().unique(),
    expiresAt: timestamptz('expires_at').notNull(),
    ipAddress: text('ip_address'),
    userAgent: text('user_agent'),
    ...timestamps,
  },
  (t) => [
    index('sessions_user_id_idx').on(t.userId),
    index('sessions_expires_at_idx').on(t.expiresAt),
  ],
);

export const accounts = pgTable(
  'accounts',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** `credential` (email + password) or `google`. */
    providerId: text('provider_id').notNull(),
    /** Google `sub`, or the user id for credentials. */
    accountId: text('account_id').notNull(),
    /** argon2id hash, `credential` accounts only. */
    password: text('password'),
    // Always NULL for Google: login only proves identity; tokens are stripped (ADR-0004).
    accessToken: text('access_token'),
    refreshToken: text('refresh_token'),
    idToken: text('id_token'),
    accessTokenExpiresAt: timestamptz('access_token_expires_at'),
    refreshTokenExpiresAt: timestamptz('refresh_token_expires_at'),
    scope: text('scope'),
    ...timestamps,
  },
  (t) => [
    unique('accounts_provider_account_unique').on(t.providerId, t.accountId),
    index('accounts_user_id_idx').on(t.userId),
  ],
);

export const verifications = pgTable(
  'verifications',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    /** Hashed by Better Auth (`storeIdentifier: "hashed"`); reset tokens and OAuth state. */
    identifier: text('identifier').notNull(),
    value: text('value').notNull(),
    expiresAt: timestamptz('expires_at').notNull(),
    ...timestamps,
  },
  (t) => [
    index('verifications_identifier_idx').on(t.identifier),
    index('verifications_expires_at_idx').on(t.expiresAt),
  ],
);

// ---------------------------------------------------------------------------------------------
// Availability. Maps 1:1 onto the slot engine's inputs (packages/core). Times are wall-clock in
// the schedule's zone; an end of '24:00' means midnight at the end of the day.
// ---------------------------------------------------------------------------------------------

export const schedules = pgTable(
  'schedules',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    name: text('name').notNull(),
    /** IANA time zone, validated in the app; defaults to the owner's. */
    timeZone: text('time_zone').notNull(),
    ...timestamps,
  },
  (t) => [
    unique('schedules_owner_name_unique').on(t.ownerId, t.name),
    // Target of composite FKs that guarantee "same owner".
    unique('schedules_id_owner_unique').on(t.id, t.ownerId),
  ],
);

export const scheduleRules = pgTable(
  'schedule_rules',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    scheduleId: uuid('schedule_id')
      .notNull()
      .references(() => schedules.id, { onDelete: 'cascade' }),
    /** ISO weekday, as Temporal's `dayOfWeek`: 1 = Monday ... 7 = Sunday. */
    weekday: smallint('weekday').notNull(),
    startTime: time('start_time').notNull(),
    endTime: time('end_time').notNull(),
  },
  (t) => [
    check('schedule_rules_weekday', sql`${t.weekday} BETWEEN 1 AND 7`),
    check('schedule_rules_valid_range', sql`${t.endTime} > ${t.startTime}`),
    index('schedule_rules_schedule_weekday_idx').on(t.scheduleId, t.weekday),
  ],
);

export const dateOverrides = pgTable(
  'date_overrides',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    scheduleId: uuid('schedule_id')
      .notNull()
      .references(() => schedules.id, { onDelete: 'cascade' }),
    date: date('date').notNull(),
  },
  // One override per date, as the slot engine requires.
  (t) => [unique('date_overrides_schedule_date_unique').on(t.scheduleId, t.date)],
);

/** An override with no ranges blocks the whole day. */
export const dateOverrideRanges = pgTable(
  'date_override_ranges',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    overrideId: uuid('override_id')
      .notNull()
      .references(() => dateOverrides.id, { onDelete: 'cascade' }),
    startTime: time('start_time').notNull(),
    endTime: time('end_time').notNull(),
  },
  (t) => [
    check('date_override_ranges_valid_range', sql`${t.endTime} > ${t.startTime}`),
    index('date_override_ranges_override_id_idx').on(t.overrideId),
  ],
);

// ---------------------------------------------------------------------------------------------
// Event types
// ---------------------------------------------------------------------------------------------

export const locationKind = pgEnum('location_kind', [
  'jitsi',
  'google_meet',
  'in_person',
  'phone',
  'link',
]);

export const eventTypes = pgTable(
  'event_types',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    scheduleId: uuid('schedule_id').notNull(),
    slug: text('slug').notNull(),
    title: text('title').notNull(),
    description: text('description'),
    durationMinutes: integer('duration_minutes').notNull(),
    bufferBeforeMinutes: integer('buffer_before_minutes').notNull().default(0),
    bufferAfterMinutes: integer('buffer_after_minutes').notNull().default(0),
    minimumNoticeMinutes: integer('minimum_notice_minutes').notNull().default(0),
    /** Max bookings per owner-local day; NULL = unlimited. */
    dailyLimit: integer('daily_limit'),
    /** Step between slot starts; NULL = the duration. */
    slotIntervalMinutes: integer('slot_interval_minutes'),
    locationKind: locationKind('location_kind').notNull(),
    /** Address, phone number or URL; generated for video kinds. */
    locationDetails: text('location_details'),
    active: boolean('active').notNull().default(true),
    ...timestamps,
  },
  (t) => [
    unique('event_types_owner_slug_unique').on(t.ownerId, t.slug),
    unique('event_types_id_owner_unique').on(t.id, t.ownerId),
    // The schedule must belong to the same owner. Deleting a schedule in use is rejected.
    foreignKey({
      name: 'event_types_schedule_same_owner_fk',
      columns: [t.scheduleId, t.ownerId],
      foreignColumns: [schedules.id, schedules.ownerId],
    }).onDelete('restrict'),
    index('event_types_schedule_idx').on(t.scheduleId, t.ownerId),
    check('event_types_slug_format', sql`${t.slug} ~ '^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$'`),
    check('event_types_duration', sql`${t.durationMinutes} BETWEEN 1 AND 1440`),
    check('event_types_buffer_before', sql`${t.bufferBeforeMinutes} BETWEEN 0 AND 1440`),
    check('event_types_buffer_after', sql`${t.bufferAfterMinutes} BETWEEN 0 AND 1440`),
    check('event_types_minimum_notice', sql`${t.minimumNoticeMinutes} >= 0`),
    check('event_types_daily_limit', sql`${t.dailyLimit} > 0`),
    check('event_types_slot_interval', sql`${t.slotIntervalMinutes} BETWEEN 1 AND 1440`),
    check(
      'event_types_location_details',
      sql`${t.locationKind} IN ('jitsi', 'google_meet') OR ${t.locationDetails} IS NOT NULL`,
    ),
  ],
);

// ---------------------------------------------------------------------------------------------
// Calendar connections. Credentials are AES-256-GCM encrypted (key from env), never logged.
// ---------------------------------------------------------------------------------------------

export const calendarProvider = pgEnum('calendar_provider', ['google', 'caldav']);

export const connectionStatus = pgEnum('connection_status', [
  'pending',
  'active',
  'needs_reauth',
  'disabled',
]);

export const calendarConnections = pgTable(
  'calendar_connections',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    provider: calendarProvider('provider').notNull(),
    /** Google `sub` or CalDAV username. */
    accountIdentifier: text('account_identifier').notNull(),
    displayName: text('display_name').notNull(),
    caldavUrl: text('caldav_url'),
    /** version || iv || auth tag || ciphertext. */
    credentials: bytea('credentials').notNull(),
    /** Which encryption key encrypted `credentials`, for key rotation. */
    credentialsKeyVersion: smallint('credentials_key_version').notNull(),
    status: connectionStatus('status').notNull().default('pending'),
    lastSyncedAt: timestamptz('last_synced_at'),
    /** Never contains secrets. */
    lastError: text('last_error'),
    ...timestamps,
  },
  (t) => [
    unique('calendar_connections_owner_account_unique').on(
      t.ownerId,
      t.provider,
      t.accountIdentifier,
    ),
    unique('calendar_connections_id_owner_unique').on(t.id, t.ownerId),
    check(
      'calendar_connections_caldav_url',
      sql`(${t.provider} = 'caldav') = (${t.caldavUrl} IS NOT NULL)`,
    ),
  ],
);

export const calendars = pgTable(
  'calendars',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    ownerId: uuid('owner_id').notNull(),
    connectionId: uuid('connection_id').notNull(),
    /** Google calendar id or CalDAV calendar URL. */
    externalId: text('external_id').notNull(),
    name: text('name').notNull(),
    /** Busy times from this calendar block slots. */
    checkConflicts: boolean('check_conflicts').notNull().default(true),
    /** Bookings are written to this calendar (at most one per owner). */
    isBookingTarget: boolean('is_booking_target').notNull().default(false),
  },
  (t) => [
    unique('calendars_connection_external_unique').on(t.connectionId, t.externalId),
    foreignKey({
      name: 'calendars_connection_same_owner_fk',
      columns: [t.connectionId, t.ownerId],
      foreignColumns: [calendarConnections.id, calendarConnections.ownerId],
    }).onDelete('cascade'),
    uniqueIndex('calendars_one_booking_target_per_owner')
      .on(t.ownerId)
      .where(sql`${t.isBookingTarget}`),
  ],
);

