export const bookingStatus = pgEnum('booking_status', ['confirmed', 'cancelled']);

/**
 * Double booking is impossible at the DB level: `bookings_no_overlap`
 * (EXCLUDE USING gist on owner_id + during, ignoring cancelled rows) is created in a
 * custom migration because Drizzle cannot express exclusion constraints. ADR-0002.
 */
export const bookings = pgTable(
  'bookings',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    // RESTRICT: deleting an account must cancel and notify first (ADR-0004 plan).
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => users.id, { onDelete: 'restrict' }),
    eventTypeId: uuid('event_type_id').notNull(),
    status: bookingStatus('status').notNull().default('confirmed'),
    startAt: timestamptz('start_at').notNull(),
    endAt: timestamptz('end_at').notNull(),
    // Half-open so back-to-back bookings (one ends 10:00, next starts 10:00) never conflict.
    during: tstzrange('during')
      .notNull()
      .generatedAlwaysAs(sql`tstzrange(start_at, end_at, '[)')`),
    guestName: text('guest_name').notNull(),
    guestEmail: text('guest_email').notNull(),
    /** IANA time zone of the guest, for emails and reminders. */
    guestTimeZone: text('guest_time_zone').notNull(),
    /** SHA-256 (base64url) of the token in the guest's cancel/reschedule link. */
    manageTokenHash: text('manage_token_hash').notNull().unique(),
    cancelledAt: timestamptz('cancelled_at'),
    cancellationReason: text('cancellation_reason'),
    rescheduledFromId: uuid('rescheduled_from_id').references((): AnyPgColumn => bookings.id, {
      onDelete: 'set null',
    }),
    ...timestamps,
  },
  (t) => [
    check('bookings_valid_range', sql`${t.endAt} > ${t.startAt}`),
    check(
      'bookings_cancelled_at',
      sql`(${t.status} = 'cancelled') = (${t.cancelledAt} IS NOT NULL)`,
    ),
    // The event type must belong to the same owner.
    foreignKey({
      name: 'bookings_event_type_same_owner_fk',
      columns: [t.eventTypeId, t.ownerId],
      foreignColumns: [eventTypes.id, eventTypes.ownerId],
    }).onDelete('restrict'),
    // Daily-limit counts per event type.
    index('bookings_event_type_start_idx').on(t.eventTypeId, t.startAt),
  ],
);

